INK, MUTE, RED, BG = RGBColor(0x14, 0x18, 0x1f), RGBColor(0x66, 0x70, 0x85), RGBColor(0xd6, 0x2e, 0x2e), RGBColor(0xf4, 0xf5, 0xf7)
prs = Presentation(); prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)

def slide(title, sub=None):
    s = prs.slides.add_slide(prs.slide_layouts[6])
    s.background.fill.solid(); s.background.fill.fore_color.rgb = RGBColor(255, 255, 255)
    bar = s.shapes.add_shape(1, 0, 0, Inches(0.25), prs.slide_height); bar.fill.solid(); bar.fill.fore_color.rgb = RED; bar.line.fill.background()
    tb = s.shapes.add_textbox(Inches(0.7), Inches(0.4), Inches(12), Inches(1.0)).text_frame; tb.word_wrap = True
    p = tb.paragraphs[0]; p.text = title; p.font.size = Pt(32); p.font.bold = True; p.font.color.rgb = INK
    if sub:
        p2 = tb.add_paragraph(); p2.text = sub; p2.font.size = Pt(16); p2.font.color.rgb = MUTE
    return s

def text(s, x, y, w, h, lines, size=20, color=INK, bold_first=False):
    tf = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h)).text_frame; tf.word_wrap = True
    for i, l in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = l; p.font.size = Pt(size); p.font.color.rgb = color; p.space_after = Pt(8)
        if bold_first and i == 0: p.font.bold = True
    return tf

def stat(s, x, y, big, small, w=3.9):
    box = s.shapes.add_shape(1, Inches(x), Inches(y), Inches(w), Inches(1.9)); box.fill.solid(); box.fill.fore_color.rgb = BG; box.line.fill.background()
    text(s, x + 0.2, y + 0.1, w - 0.4, 0.9, [big], size=34, color=RED)
    text(s, x + 0.2, y + 0.95, w - 0.4, 0.9, [small], size=14, color=MUTE)

