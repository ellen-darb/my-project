export function pl(n, one, few, many) {
  n = Math.abs(Math.round(n)); const m10 = n % 10, m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
}

/* интервал между составами в одном направлении по парности: 30 пар/ч -> 2:00 */
export function interval(pairs) {
  if (!(pairs > 0)) return "—";
  const s = Math.round(3600 / pairs);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

/* тексты расчёта — языком диспетчерской, без «пар/ч» и сокращений */
export function plain(t) {
  return t

    .replace("по графику парность снижается, а поток ещё выше нормы; составы уже на линии, ввод не нужен", "График убирает составы, а людей ещё больше нормы. Составы уже на линии, их достаточно не уводить")
    .replace(/^Составы не добавлять: к центру до (\d[\d ]*) чел\. в составе \((\d+)% нормы\)/, "Добавлять составы не нужно: в составе до $1 человек, это $2% нормы")
    .replace("Людей больше обычного, загрузку составов по входам оценить нельзя", "Людей больше обычного. Загрузку составов по входам не оцениваем, ориентируйтесь на доклады станций")
    .replace("поток выше обычного, но там, где загрузку можно оценить, место есть; по центру и вечером — доклады дежурных станций", "Людей больше обычного, но в составах есть место. В центре и вечером ориентируйтесь на доклады дежурных")
    .replace(/^людей на (\d+)% меньше обычного/, "Людей на $1% меньше обычного")
    .replace(/^выше нормы меньше двух четвертей часа подряд; следите за докладами станций/, "Выше нормы меньше получаса подряд: следите за докладами станций")
    .replace("поток выше обычного; вне утреннего пика нужны выходы по станциям, по входам загрузку не оцениваем", "Людей больше обычного. Вне утреннего пика нужны выходы по станциям, по входам загрузку не оцениваем")
    .replace(/^резерв выходит за (\d+)–(\d+) мин и успевает; начало с (\d\d:\d\d)/, "Резервный состав выезжает за $1–$2 мин и успевает: выйдет на линию к $3")
    .replace(/^тесно станет через (\d+) мин: резерв успеет к (\d\d:\d\d), дальше окно ещё идёт/, "Тесно станет через $1 мин, резерв успеет к $2: поможет со второй половины пика")
    .replace(/^Резерв не успеет: тесно станет через (\d+) мин, состав выйдет не раньше (\d\d:\d\d)/, "Резерв не успеет: тесно станет через $1 мин, а состав выйдет не раньше $2")
    .replace("предупредите станции участка и дежурных по станции; выпуск новых составов уже не поможет", "Предупредите станции участка: новый состав уже не выйдет вовремя")
    .replace(/(Не снимать составы|Продлить удержание составов) до (\d\d:\d\d): держать (\d+) пар\/ч/, (m, w, h, n) => `${w} до ${h}: держать интервал ${interval(+n)}`)
    .replace(/Выпустить (\d+) сост\. раньше графика из депо ([^,]+), \+(\d+) пар\/ч/, (m, n, d) => `Выпустить ${n} ${pl(n, "состав", "состава", "составов")} из депо ${d} раньше графика`)
    .replace(/Выдать (\d+) сост\. из резерва депо ([^,]+), \+(\d+) пар\/ч/, (m, n, d) => `Выпустить ${n} ${pl(n, "резервный состав", "резервных состава", "резервных составов")} из депо ${d}`)
    .replace(/Снять (\d+) сост\. в депо, −(\d+) пар\/ч/, (m, n) => `Отправить ${n} ${pl(n, "состав", "состава", "составов")} в депо`);
}
