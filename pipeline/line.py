def schedule_for(date) -> str:
    """Какой лист графика действует в день. Для февраля и мая берём учебный рабочий график (как с 01.09):
    листов зимнего графика у нас нет — допущение."""
    if date.weekday() >= 5 or date.strftime("%Y-%m-%d") in HOLIDAYS:
        return "weekend"
    if 6 <= date.month <= 8:
        return "weekday_summer"
    return "weekday_sep"


def day_group(date) -> str:
    if date.strftime("%Y-%m-%d") in HOLIDAYS:
        return "sun"
    wd = date.weekday()
    return "mon-thu" if wd < 4 else ("fri" if wd == 4 else ("sat" if wd == 5 else "sun"))


def pairs_at(sched: str, minute: int) -> float:
    """Пар поездов в час в момент minute (минуты от полуночи)."""
    h = (minute // 60) % 24
    if h not in HOURS:
        return 0.0
    p = SCHEDULES[sched]["pairs"][HOURS.index(h)]
    return float(p)


def trains_at(sched: str, minute: int) -> int:
    h = (minute // 60) % 24
    return SCHEDULES[sched]["trains"][HOURS.index(h)] if h in HOURS else 0


